"""Run every numerical verification and write results/verification_report.{json,md}."""
import json
import platform

import numpy as np

from _common import RESULTS
from src import verification as V

report = {
    "environment": {"python": platform.python_version(), "numpy": np.__version__},
    "fk_vs_mujoco": V.fk_vs_mujoco(n=2000, seed=0),
    "ik_roundtrip": V.ik_roundtrip(n=3000, seed=1),
    "ik_edge_cases": V.ik_edge_cases(seed=2),
    "ik_analytic_vs_numerical": V.ik_analytic_vs_numerical(n=100, seed=4),
    "jacobian_vs_numerical": V.jacobian_vs_numerical(n=1000, seed=3),
    "velocity_kinematics": V.velocity_checks(n=500, seed=6),
}
ex = V.singularity_examples()
report["singularity_examples"] = {k: dict(status=v.status, sigma_min=v.svd.sigma_min, rank=v.svd.rank,
                                          condition_number=v.svd.condition_number, active=v.active)
                                  for k, v in ex.items()}
(RESULTS / "verification_report.json").write_text(json.dumps(report, indent=2, default=float))

f, i, e, j = report["fk_vs_mujoco"], report["ik_roundtrip"], report["ik_edge_cases"], report["jacobian_vs_numerical"]
lines = ["# Verification report (generated by examples/verification_report.py)", ""]
lines += [f"## FK vs MuJoCo  ({f['n']} random valid configs, seed {f['seed']})",
          f"- position error [m]: max {f['position_error_m']['max']:.2e}, RMS {f['position_error_m']['rms']:.2e}",
          f"- orientation error [rad]: max {f['orientation_error_rad']['max']:.2e}, RMS {f['orientation_error_rad']['rms']:.2e}",
          f"- wrist-centre error [m]: max {f['wrist_center_error_m']['max']:.2e}", ""]
lines += [f"## IK round trip  ({i['n']} random valid configs, seed {i['seed']})",
          f"- original configuration recovered: {i['recovered_original']}/{i['n']}",
          f"- geometric branches per target (histogram): {i['branch_count_histogram']}",
          f"- branches inside joint limits per target (histogram): {i['feasible_count_histogram']}",
          f"- FK check of every branch: position max {i['position_error_m']['max']:.2e} m (RMS {i['position_error_m']['rms']:.2e}), "
          f"orientation max {i['orientation_error_rad']['max']:.2e} rad (RMS {i['orientation_error_rad']['rms']:.2e})", ""]
lines += ["## IK edge cases", "```", json.dumps(e, indent=1, default=float), "```", ""]
lines += [f"## Analytic vs secondary numerical IK: {report['ik_analytic_vs_numerical']}", ""]
lines += [f"## Jacobian vs central finite differences ({j['n']} configs, seed {j['seed']})",
          f"- all entries: max |err| {j['all']['max_abs']:.2e}, RMS {j['all']['rms']:.2e}",
          f"- translational block: max {j['translational']['max_abs']:.2e}, RMS {j['translational']['rms']:.2e}",
          f"- rotational block: max {j['rotational']['max_abs']:.2e}, RMS {j['rotational']['rms']:.2e}",
          f"- |det J - closed form a2*X*v*sin(q5)| max {j['determinant_vs_closed_form_max']:.2e}", ""]
vk = report["velocity_kinematics"]
lines += [f"## Velocity kinematics ({vk['n']} configs, seed {vk['seed']})",
          f"- ellipsoid semi-axes^2 vs eigenvalues of J_part J_part^T: max |diff| {vk['ellipsoid_axes_vs_eig_max_err']:.2e}",
          f"- directional gain outside [smallest, largest] semi-axis: max violation {vk['directional_gain_bound_violation']:.2e}",
          f"- twist -> qdot -> twist round trip (pseudo-inverse): max error {vk['twist_roundtrip_max_err']:.2e}"]
for k in ("shoulder", "elbow", "wrist"):
    v = vk[f"singular_{k}"]
    lines.append(f"- singular {k}: lost-direction alignment >= {v['lost_direction_alignment_min']:.6f}, "
                 f"|J * self-motion| <= {v['null_motion_residual_max']:.1e}")
lines.append(f"- joint speed for the weakest twist near the wrist singularity (DLS bound {vk['dls_bound_1_over_2lambda']:.0f} rad/s):")
for r in vk["joint_speed_weakest_twist"]:
    lines.append(f"  - q5={r['q5']:g}: sigma_min={r['sigma_min']:.2e}, pseudo-inverse {r['pinv_speed']:.3e} rad/s, DLS {r['dls_speed']:.3f} rad/s")
lines.append("")
lines += ["## Singularity examples"]
for k, v in report["singularity_examples"].items():
    lines.append(f"- {k}: {v['status']}, sigma_min={v['sigma_min']:.2e}, rank={v['rank']}, cond={v['condition_number']:.2e}, active={v['active']}")
(RESULTS / "verification_report.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
